import { test, expect } from '@playwright/test'

test('subpath deployment supports checking, reviewing, applying and recovery', async ({ page }) => {
  const browserErrors: string[] = []
  page.on('pageerror', error => browserErrors.push(error.message))
  await page.goto('./')
  await page.getByLabel('Administrator password').fill('browser-fixture-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
  await page.getByRole('switch', { name: 'Advanced mode' }).check()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('switch', { name: /scanning/ }).uncheck()
  for (const name of ['Automatic DAT references', 'Identify unknown formats'])
    await page.getByRole('switch', { name: new RegExp(name) }).uncheck()
  await page.getByText('Advanced engine & server settings', { exact: true }).click()
  await page.getByLabel('Hasheous lookup').selectOption('Off')
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Settings saved' })).toBeVisible()
  await page.getByRole('button', { name: 'Server tools', exact: true }).click()
  await page.getByRole('button', { name: 'Check library', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Detailed results', exact: true })).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Browser fixture.nes', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Disabled')
  await page.getByRole('button', { name: 'Mark original', exact: true }).click()
  await page.getByRole('button', { name: 'Move previews', exact: true }).click()
  await expect(page.getByText('1 draft review decision(s) need a rebuilt preview.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Apply moves' })).toBeDisabled()
  await page.getByRole('button', { name: 'Rebuild preview' }).click()
  await expect(page.getByRole('heading', { name: 'Move previews', exact: true })).toBeVisible({ timeout: 60_000 })
  await page.getByRole('button', { name: 'Apply moves' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  // Exercise polling recovery when a proxy drops the live event connection.
  await page.route('**/api/jobs/*/events', route => route.abort())
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Detailed results', exact: true })).toBeVisible({ timeout: 60_000 })
  await page.unroute('**/api/jobs/*/events')
  await page.getByRole('button', { name: 'Recovery', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh journals' }).click()
  await expect(page.getByRole('status')).toContainText('Load recovery journals finished', { timeout: 60_000 })
  await page.getByRole('button', { name: 'Recovery', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Preview undo' })).toBeVisible()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Restore files finished', { timeout: 60_000 })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Library', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Library', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('overview-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: test.info().outputPath('overview-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Use light theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: test.info().outputPath('overview-light.png'), fullPage: true })
  expect(browserErrors).toEqual([])
})
